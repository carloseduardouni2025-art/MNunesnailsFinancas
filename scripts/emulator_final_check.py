from emulator_ui import *
from datetime import date
import calendar

today = date.fromisoformat(adb('shell','date','+%Y-%m-%d'))
tap('Previous month', 'content-desc')
prior_year = today.year if today.month > 1 else today.year - 1
prior_month = today.month - 1 if today.month > 1 else 12
prior_day = min(today.day, calendar.monthrange(prior_year, prior_month)[1])
tap(str(prior_day))
tap('OK')
expected = date(prior_year, prior_month, prior_day).isoformat()
tap('Salvar', 'content-desc', scroll=True)
assert records()['incomes'][-1]['date'] == expected
find('↑ +0% em relação ao mês anterior')
assert sum(item['cents'] for item in records()['incomes']) == 9000
screenshot('12-home-dark-final')
print('PASS: calendario, mes anterior, total R$90 e comparacao mensal', flush=True)
tap('Registrar Receita','content-desc')
tap('Selecione o serviço')
tap('Manicure')
tap('Cancelar','content-desc',scroll=True)
assert len(records()['incomes']) == 2
print('PASS: cancelamento de receita nao cria registro', flush=True)
tap('Serviços','content-desc')
find('Manicure')
screenshot('13-services-dark')
adb('shell','cmd','uimode','night','no')
time.sleep(1)
find('Manicure')
screenshot('14-services-light')
adb('shell','input','keyevent','KEYCODE_BACK')
find('Olá!')
screenshot('15-home-light-final')
tap('Abrir menu','content-desc')
screenshot('16-menu-light')
tap('Receitas')
find('Seus recebimentos')
screenshot('17-receipts-light')
adb('shell','input','keyevent','KEYCODE_BACK')
find('Olá!')
print('PASS: telas de servicos e receitas, menu e Voltar', flush=True)
adb('shell','wm','size','720x1280')
adb('shell','wm','density','320')
time.sleep(1)
find('Novo lançamento','content-desc')
screenshot('18-home-compact')
tap('Cadastrar Serviço','content-desc',scroll=True)
fill('Nome do serviço','Rascunho compacto')
fill('Valor do serviço','50.00')
tap('Valor do serviço','content-desc',scroll=True)
time.sleep(3)
assert 'mInputShown=true' in adb('shell','dumpsys','input_method')
screenshot('19-keyboard-compact')
adb('shell','input','keyevent','KEYCODE_BACK')
tap('Cancelar','content-desc',scroll=True)
assert len(records()['services']) == 1
adb('shell','wm','size','reset')
adb('shell','wm','density','reset')
adb('shell','am','force-stop',PACKAGE)
adb('shell','am','start','-n',PACKAGE+'/.MainActivity')
time.sleep(1)
find('Serviços cadastrados: 1')
assert len(records()['services']) == 1 and len(records()['incomes']) == 2
print('PASS: tela compacta, teclado e persistencia apos force-stop', flush=True)
(OUT/'records.json').write_text(json.dumps(records(), ensure_ascii=False, indent=2), encoding='utf-8')
(OUT/'crash-log.txt').write_text(adb('logcat','-b','crash','-d'),encoding='utf-8')
print('EMULATOR CHECKLIST PASSED', flush=True)
